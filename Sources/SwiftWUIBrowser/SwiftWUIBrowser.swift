// SwiftWUIBrowser - Browser API utilities for SwiftWUI
//
// This module provides Swift wrappers around common browser APIs:
//
// - ``AppStorage``: Property wrapper for browser localStorage
// - ``SessionStorage``: Property wrapper for browser sessionStorage
// - ``GeolocationManager``: Browser Geolocation API
// - ``ClipboardManager``: Browser Clipboard API
// - ``MediaQueryState``: Responsive design media queries
// - ``LocalizedStringCatalog``: Internationalization (i18n)
